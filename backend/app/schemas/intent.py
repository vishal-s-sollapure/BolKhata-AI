"""Pydantic schemas for AI intent parsing and transaction proposals in BolKhata AI."""

from decimal import Decimal
from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field, field_serializer, field_validator, model_validator


class IntentType(str, Enum):
    """Supported user voice intent types in BolKhata AI."""
    ADD_CREDIT = "ADD_CREDIT"
    RECORD_PAYMENT = "RECORD_PAYMENT"
    CHECK_BALANCE = "CHECK_BALANCE"
    LIST_RECENT_TRANSACTIONS = "LIST_RECENT_TRANSACTIONS"
    UNKNOWN = "UNKNOWN"


class ReasoningCode(str, Enum):
    """Standardized machine-readable explanation codes for parsing outcomes."""
    CUSTOMER_AND_AMOUNT_IDENTIFIED = "CUSTOMER_AND_AMOUNT_IDENTIFIED"
    CUSTOMER_IDENTIFIED_FOR_BALANCE = "CUSTOMER_IDENTIFIED_FOR_BALANCE"
    RECENT_TRANSACTIONS_REQUESTED = "RECENT_TRANSACTIONS_REQUESTED"
    MISSING_CUSTOMER_NAME = "MISSING_CUSTOMER_NAME"
    MISSING_AMOUNT = "MISSING_AMOUNT"
    INVALID_AMOUNT = "INVALID_AMOUNT"
    AMBIGUOUS_TRANSACTION_TYPE = "AMBIGUOUS_TRANSACTION_TYPE"
    MULTIPLE_TRANSACTIONS_DETECTED = "MULTIPLE_TRANSACTIONS_DETECTED"
    UNKNOWN_INTENT = "UNKNOWN_INTENT"
    LLM_PARSING_ERROR = "LLM_PARSING_ERROR"


class TransactionProposal(BaseModel):
    """A validated transaction proposal generated by the AI intent parser.
    
    IMPORTANT: This represents a proposed financial action awaiting explicit
    merchant confirmation. It NEVER directly mutates the database.
    """
    intent: IntentType = Field(..., description="Categorized user intent")
    customer_name: Optional[str] = Field(None, description="Preserved customer name or identifier")
    amount: Optional[Decimal] = Field(None, description="Monetary transaction amount in INR")
    currency: str = Field("INR", description="Supported currency code (must be INR)")
    language: Optional[str] = Field(None, description="Language code of source transcript (e.g. kn-IN, hi-IN, en-IN)")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Model parsing confidence score (0.0 to 1.0)")
    requires_clarification: bool = Field(False, description="Whether merchant clarification is needed before confirming")
    clarification_question: Optional[str] = Field(None, description="Clarification question to ask the shopkeeper if needed")
    summary: str = Field(..., description="Human-readable summary of the proposed transaction")
    reasoning_code: str = Field(..., description="Machine-readable reasoning code explaining the proposal")

    @field_serializer("amount")
    def serialize_amount(self, value: Optional[Decimal]) -> Optional[str]:
        """Serializes Decimal amount to string with 2 decimal places to avoid float rounding."""
        if value is None:
            return None
        return f"{value:.2f}"

    @field_validator("amount")
    @classmethod
    def validate_positive_amount(cls, value: Optional[Decimal]) -> Optional[Decimal]:
        """Ensures that if an amount is present, it is strictly positive."""
        if value is not None:
            if value <= Decimal("0"):
                raise ValueError("Amount must be strictly greater than zero.")
            # Quantize to 2 decimal places
            return value.quantize(Decimal("0.01"))
        return None

    @field_validator("currency")
    @classmethod
    def validate_inr_currency(cls, value: str) -> str:
        """Enforces INR as the sole supported currency."""
        if value.upper() != "INR":
            raise ValueError(f"Unsupported currency '{value}'. Only 'INR' is supported.")
        return "INR"

    @model_validator(mode="after")
    def validate_proposal_integrity(self) -> "TransactionProposal":
        """Enforces domain integrity rules across fields."""
        # Clean customer_name string
        if self.customer_name is not None:
            cleaned = self.customer_name.strip()
            self.customer_name = cleaned if cleaned else None

        # Rule 1: ADD_CREDIT and RECORD_PAYMENT require both customer_name and amount
        if self.intent in (IntentType.ADD_CREDIT, IntentType.RECORD_PAYMENT):
            action_desc = "credit" if self.intent == IntentType.ADD_CREDIT else "payment"
            if not self.customer_name:
                self.requires_clarification = True
                self.reasoning_code = ReasoningCode.MISSING_CUSTOMER_NAME.value
                self.clarification_question = f"Which customer should this {action_desc} be recorded for?"
            elif self.amount is None:
                self.requires_clarification = True
                self.reasoning_code = ReasoningCode.MISSING_AMOUNT.value
                self.clarification_question = f"What is the {action_desc} amount for {self.customer_name}?"

        # Rule 2: CHECK_BALANCE requires customer_name and no amount
        elif self.intent == IntentType.CHECK_BALANCE:
            if not self.customer_name:
                self.requires_clarification = True
                self.reasoning_code = ReasoningCode.MISSING_CUSTOMER_NAME.value
                self.clarification_question = "Which customer's balance would you like to check?"
            self.amount = None  # Force amount to None for balance queries

        # Rule 3: LIST_RECENT_TRANSACTIONS does not require customer or amount
        elif self.intent == IntentType.LIST_RECENT_TRANSACTIONS:
            self.amount = None

        # Rule 4: UNKNOWN must never be executable
        elif self.intent == IntentType.UNKNOWN:
            self.requires_clarification = True
            if not self.clarification_question:
                self.clarification_question = "I could not understand the request. Please specify the customer name and transaction details."
            if not self.reasoning_code:
                self.reasoning_code = ReasoningCode.UNKNOWN_INTENT.value

        return self

    @property
    def is_executable(self) -> bool:
        """Returns True only if the proposal is unambiguous and ready for shopkeeper confirmation."""
        if self.requires_clarification:
            return False
        if self.intent == IntentType.UNKNOWN:
            return False
        if self.intent in (IntentType.ADD_CREDIT, IntentType.RECORD_PAYMENT):
            return bool(self.customer_name and self.amount and self.amount > Decimal("0"))
        if self.intent == IntentType.CHECK_BALANCE:
            return bool(self.customer_name)
        if self.intent == IntentType.LIST_RECENT_TRANSACTIONS:
            return True
        return False


class ParseIntentRequest(BaseModel):
    """Request payload for intent parsing endpoint."""
    transcript: str = Field(..., min_length=1, description="Raw transcription text from Gnani Prisma v3.0")
    language: Optional[str] = Field("en-IN", description="Language code of the utterance (kn-IN, hi-IN, en-IN, indic-auto)")


class ParseIntentResponse(BaseModel):
    """Response payload returned by the intent parsing endpoint."""
    success: bool = Field(..., description="Whether parsing succeeded")
    original_transcript: str = Field(..., description="The original unmodified voice transcript")
    proposal: TransactionProposal = Field(..., description="The validated transaction proposal")
    error: Optional[str] = Field(None, description="Error message if parsing encountered an unrecoverable issue")
